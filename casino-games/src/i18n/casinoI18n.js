function applyVars(text, vars) {
  if (!vars) return text;
  return text.replace(/\{\{(\w+)\}\}/g, (_, key) => (vars[key] != null ? String(vars[key]) : ''));
}

export function setLang(l) {
  lang = l === 'en' ? 'en' : 'ar';
  try {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  } catch {
    // ignore
  }
}

export function getLang() {
  return lang;
}

export function t(key, vars) {
  const bucket = STR[lang] || STR.ar;
  const text = bucket[key] ?? STR.ar[key] ?? key;
  return applyVars(text, vars);
}

export function readLangFromUrl() {
  try {
    const q = new URLSearchParams(window.location.search || '');
    const l = q.get('lang') || q.get('locale') || '';
    if (l) setLang(l);
  } catch {
    // ignore
  }
}

export function currencyName() {
  return t('currencyName');
}
